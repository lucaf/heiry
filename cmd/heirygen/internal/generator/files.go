const (
	outputSuffix     = ".heirygen.go"
	testOutputSuffix = ".heirygen_test.go"
)

// outputName returns the name of the file generated for a source file:
// x.go gives x.heirygen.go and x_test.go gives x.heirygen_test.go. Go reads
// platform suffixes from the part of a name before its first dot, and drops
// a final _test element first, so the output is selected by exactly the
// builds that select its source.
func outputName(source string) string {
	stem := strings.TrimSuffix(source, ".go")
	if base, test := strings.CutSuffix(stem, "_test"); test {
		return base + testOutputSuffix
	}
	return stem + outputSuffix
}

// isOutput reports whether name has the form of a generated file.
func isOutput(name string) bool {
	return strings.HasSuffix(name, outputSuffix) || strings.HasSuffix(name, testOutputSuffix)
}

// A Finding is one output that check mode reports as not up to date.
type Finding struct {
	Path    string
	Problem string
}

func (f Finding) String() string { return f.Path + ": " + f.Problem }

// A Report lists the files a generation run changed.
type Report struct {
	Written, Removed []string
}

// sourceOf returns the source file whose output has this name.
func sourceOf(output string) (string, bool) {
	if base, test := strings.CutSuffix(output, testOutputSuffix); test {
		return base + "_test.go", base != ""
	}
	stem, found := strings.CutSuffix(output, outputSuffix)
	// x_test.go gives x.heirygen_test.go, so x_test.heirygen.go is no output.
	if !found || stem == "" || strings.HasSuffix(stem, "_test") {
		return "", false
	}
	return stem + ".go", true
}

// markerPrefix starts every marker this command has written, including the
// investigation prototype's.
const markerPrefix = "// Code generated by heirygen"

// state is the directory as the generator sees it before changing anything.
type state struct {
	expected map[string][]byte // outputs to write, by name
	existing map[string]owned  // outputs found, by name; all owned
	// infos describes every directory entry as it was read, without
	// following symbolic links.
	infos map[string]os.FileInfo
	// caseOf maps an output name to the obsolete owned output whose name
	// differs from it only in case: the source was renamed in case only.
	caseOf map[string]string
}

type owned struct {
	content []byte
	mode    os.FileMode
}

// inspect reads dir, classifies its files, and computes the expected
// outputs. A file is an owned output when it has the output form, is a
// regular file, and starts with the marker naming the source that output
// belongs to. Any other file with the output form, or any file with another
// name that starts with a heirygen marker, is refused: the generator never
// replaces or deletes a file it cannot show it wrote.
func inspect(dir string) (*state, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	sources := make(map[string][]byte)
	var order []string
	existing := make(map[string]owned)
	infos := make(map[string]os.FileInfo, len(entries))
	for _, entry := range entries {
		name := entry.Name()
		path := filepath.Join(dir, name)
		info, err := os.Lstat(path)
		if err != nil {
			return nil, err
		}
		infos[name] = info
		// The go command ignores these files, and so does the generator.
		if strings.HasPrefix(name, "_") || strings.HasPrefix(name, ".") || !strings.HasSuffix(name, ".go") {
			continue
		}
		if isOutput(name) {
			if !entry.Type().IsRegular() {
				return nil, errorAt(token.Position{}, "%s is not a regular file; heirygen does not replace it", path)
			}
			content, err := os.ReadFile(path)
			if err != nil {
				return nil, err
			}
			source, known := sourceOf(name)
			// A checkout may have converted line endings, so the marker line
			// may end in CRLF. Outputs are compared with CRLF read as LF.
			content = bytes.ReplaceAll(content, []byte("\r\n"), []byte("\n"))
			if !known || !bytes.HasPrefix(content, []byte(marker(source))) {
				return nil, errorAt(token.Position{}, "%s has the name of a heirygen output but does not start with its marker; heirygen does not replace or delete it: rename or remove it", path)
			}
			existing[name] = owned{content: content, mode: info.Mode().Perm()}
			continue
		}
		if entry.IsDir() {
			continue
		}
		content, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		if bytes.HasPrefix(content, []byte(markerPrefix)) {
			from := "a source file"
			if line, _, _ := strings.Cut(string(content), "\n"); strings.Contains(line, " from ") {
				from, _, _ = strings.Cut(line[strings.LastIndex(line, " from ")+len(" from "):], ";")
			}
			return nil, errorAt(token.Position{}, "%s starts with a heirygen marker but is not named as the output of %s; rename or remove it", path, from)
		}
		sources[name] = content
		order = append(order, name)
	}
	want, err := expected(dir, order, sources)
	if err != nil {
		return nil, err
	}
	st := &state{expected: want, existing: existing, infos: infos, caseOf: make(map[string]string)}
	if err := st.checkCase(dir); err != nil {
		return nil, err
	}
	return st, nil
}

// checkCase refuses output names that differ only in case from another
// entry of the directory or from each other. The go command rejects such
// pairs of file names, and a case-insensitive file system treats them as one
// file. The one exception is an obsolete owned output whose source was
// renamed in case only: the new output takes its place.
func (st *state) checkCase(dir string) error {
	outputs := make([]string, 0, len(st.expected))
	for name := range st.expected {
		outputs = append(outputs, name)
	}
	sort.Strings(outputs)
	for index, name := range outputs {
		for _, other := range outputs[index+1:] {
			if strings.EqualFold(name, other) {
				return errorAt(token.Position{}, "the outputs %s and %s differ only in case, because their sources do; rename one of the sources", filepath.Join(dir, name), other)
			}
		}
		entries := make([]string, 0, len(st.infos))
		for entry := range st.infos {
			entries = append(entries, entry)
		}
		sort.Strings(entries)
		for _, entry := range entries {
			if entry == name || !strings.EqualFold(entry, name) {
				continue
			}
			if _, ownedOutput := st.existing[entry]; ownedOutput {
				if _, wanted := st.expected[entry]; !wanted {
					st.caseOf[name] = entry
					continue
				}
			}
			return errorAt(token.Position{}, "%s differs only in case from the existing %s; the go command rejects file names that differ only in case, and some file systems treat them as one file: rename %s", filepath.Join(dir, name), entry, entry)
		}
	}
	return nil
}

// stillSame reports whether a file is still the one that was read.
func stillSame(planned, now os.FileInfo) bool {
	return os.SameFile(planned, now) && planned.ModTime().Equal(now.ModTime()) && planned.Size() == now.Size()
}

type changeKind int

const (
	missing  changeKind = iota // an expected output does not exist
	differs                    // an owned output has other content
	obsolete                   // an owned output has no specification any more
)

// A change is one output that is not up to date.
type change struct {
	name    string
	kind    changeKind
	content []byte      // what to write, for missing and differing outputs
	mode    os.FileMode // the mode to write it with
}

// changes lists the outputs that are not up to date, in name order. Check
// reports them and Generate makes them, so both modes agree by construction.
func (st *state) changes() []change {
	names := make([]string, 0, len(st.expected)+len(st.existing))
	for name := range st.expected {
		names = append(names, name)
	}
	for name := range st.existing {
		if _, wanted := st.expected[name]; !wanted {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	var changes []change
	for _, name := range names {
		want, wanted := st.expected[name]
		have, present := st.existing[name]
		switch {
		case wanted && present && bytes.Equal(want, have.content):
		case !present:
			changes = append(changes, change{name: name, kind: missing, content: want, mode: 0o644})
		case !wanted:
			changes = append(changes, change{name: name, kind: obsolete})
		default:
			changes = append(changes, change{name: name, kind: differs, content: want, mode: have.mode})
		}
	}
	return changes
}

// Check compares the outputs of dir with what Generate would write, without
// writing anything.
func Check(dir string) ([]Finding, error) {
	st, err := inspect(dir)
	if err != nil {
		return nil, err
	}
	problems := map[changeKind]string{
		missing:  "missing; run go generate",
		differs:  "differs from the expected output; run go generate",
		obsolete: "no specification produces this file; run go generate",
	}
	var findings []Finding
	for _, c := range st.changes() {
		findings = append(findings, Finding{filepath.Join(dir, c.name), problems[c.kind]})
	}
	return findings, nil
}

// A fileWriter makes the changes Generate decides on. Tests replace it to
// make individual operations fail or to act on the directory meanwhile.
type fileWriter interface {
	// writeTemp writes data to a new temporary file in dir, whose name the
	// go command ignores, and returns its path. With an error, a path that
	// is not empty names a partial file, which the caller removes.
	writeTemp(dir string, data []byte, perm os.FileMode) (string, error)
	rename(from, to string) error
	// link gives the file at from the new name to, and fails if a file of
	// that name exists. It never replaces a file.
	link(from, to string) error
	remove(path string) error
}

type osWriter struct{}

func (osWriter) writeTemp(dir string, data []byte, perm os.FileMode) (string, error) {
	file, err := os.CreateTemp(dir, ".heirygen-*.tmp")
	if err != nil {
		return "", err
	}
	path := file.Name()
	if err := fill(file, data, perm); err != nil {
		return path, err
	}
	return path, nil
}

// fill writes data to a new file, flushes it, closes it, and sets its mode.
func fill(file *os.File, data []byte, perm os.FileMode) error {
	_, err := file.Write(data)
	if err == nil {
		err = file.Sync()
	}
	if closeErr := file.Close(); err == nil {
		err = closeErr
	}
	if err == nil {
		err = os.Chmod(file.Name(), perm)
	}
	return err
}

func (osWriter) rename(from, to string) error { return os.Rename(from, to) }
func (osWriter) link(from, to string) error   { return os.Link(from, to) }
func (osWriter) remove(path string) error     { return os.Remove(path) }

var writer fileWriter = osWriter{}

// How one output is put in place.
type publishMode int

const (
	replaceOwned publishMode = iota // over the owned output of the same name
	createNew                       // under a name no file has
	renameCase                      // in place of an obsolete owned output that is the same file under another case
)

// Generate writes the outputs of dir and removes obsolete ones. Everything
// is computed and checked first, and each new or changed output is written
// to a temporary file before any is put in place, so every output is always
// a whole file. A new output is given its name with a hard link, which fails
// instead of replacing a file that appeared meanwhile; a file system without
// hard links makes the command fail before any output changes. An existing
// output is replaced by renaming, after checking that it is still the file
// that was read, and obsolete outputs are removed last after the same check.
// A change to an output between such a check and its rename or removal is
// not detected and is lost, so nothing else may change the same generated
// files while the command runs, such as an overlapping run or a branch
// switch. A failure leaves every output either as it was or as generated;
// the error says which outputs were already put in place or removed. A
// hidden file the command made and cannot remove never stops a run, but the
// error names it.
func Generate(dir string) (Report, error) {
	var report Report
	st, err := inspect(dir)
	if err != nil {
		return report, err
	}
	path := func(name string) string { return filepath.Join(dir, name) }
	type pending struct {
		change
		mode   publishMode
		caseOf string
		temp   string
	}
	var writes []*pending
	var removals []string
	keep := make(map[string]bool) // obsolete outputs that a new output replaces
	// left lists the hidden files made by this run that could not be
	// removed. Every error reports them, and so does a run that otherwise
	// succeeds.
	var left []string
	cleanup := func(name string) {
		if err := writer.remove(name); err != nil && !errors.Is(err, fs.ErrNotExist) {
			left = append(left, fmt.Sprintf("%s (%v)", name, err))
		}
	}
	leftover := func() string {
		if len(left) == 0 {
			return ""
		}
		return "; heirygen could not remove the hidden files " + strings.Join(left, ", ") + ", which the go command ignores: delete them"
	}
	discard := func() {
		for _, w := range writes {
			if w.temp != "" {
				cleanup(w.temp)
			}
		}
	}
	needsLink := false
	for _, c := range st.changes() {
		if c.kind == obsolete {
			removals = append(removals, c.name)
			continue
		}
		w := &pending{change: c, mode: replaceOwned}
		if c.kind == missing {
			w.mode = createNew
			if old := st.caseOf[c.name]; old != "" {
				// The new output takes the old one's place and keeps its
				// permission bits. On a case-insensitive file system the new
				// name is the old output's file; elsewhere they are two files.
				w.change.mode = st.infos[old].Mode().Perm()
				if now, err := os.Lstat(path(c.name)); err == nil && os.SameFile(now, st.infos[old]) {
					w.mode, w.caseOf = renameCase, old
					keep[old] = true
				}
			}
			needsLink = true
		}
		temp, err := writer.writeTemp(dir, w.content, w.change.mode)
		if err != nil {
			if temp != "" {
				cleanup(temp)
			}
			discard()
			return report, fmt.Errorf("writing %s: %w; no output was changed%s", path(c.name), err, leftover())
		}
		w.temp = temp
		writes = append(writes, w)
	}
	if needsLink {
		// Check that the file system has hard links before anything is put
		// in place, by linking a temporary file to another hidden name.
		probe := writes[0].temp + ".link"
		if err := writer.link(writes[0].temp, probe); err != nil {
			discard()
			return report, fmt.Errorf("putting a new output in place needs a hard link, so that it never replaces a file that appears meanwhile, and linking in %s failed: %w; no output was changed%s", dir, err, leftover())
		}
		cleanup(probe)
	}
	fail := func(w *pending, format string, args ...any) (Report, error) {
		discard()
		return report, fmt.Errorf("%s: %s; %s, and every other output is unchanged%s", path(w.name), fmt.Sprintf(format, args...), progress(report), leftover())
	}
	for _, w := range writes {
		switch w.mode {
		case replaceOwned:
			if now, err := os.Lstat(path(w.name)); err != nil || !stillSame(st.infos[w.name], now) {
				return fail(w, "it changed after heirygen read it, so it was not replaced")
			}
			if err := writer.rename(w.temp, path(w.name)); err != nil {
				return fail(w, "replacing it: %v", err)
			}
			w.temp = ""
		case createNew:
			if err := writer.link(w.temp, path(w.name)); err != nil {
				if errors.Is(err, fs.ErrExist) {
					return fail(w, "it was created after heirygen read the directory, so it was not replaced")
				}
				return fail(w, "linking it into place: %v", err)
			}
			cleanup(w.temp)
			w.temp = ""
		case renameCase:
			// Move the old output aside under a hidden name, give the new one
			// its name with a link, then remove the old one. If the link
			// fails, the old output is linked back under its name, so a later
			// run finds the directory as this one did; if that name is taken
			// meanwhile, the old output stays under the hidden name.
			if now, err := os.Lstat(path(w.caseOf)); err != nil || !stillSame(st.infos[w.caseOf], now) {
				return fail(w, "%s changed after heirygen read it, so it was not replaced", w.caseOf)
			}
			aside := w.temp + ".old"
			if err := writer.rename(path(w.caseOf), aside); err != nil {
				return fail(w, "moving %s aside: %v", w.caseOf, err)
			}
			if err := writer.link(w.temp, path(w.name)); err != nil {
				cause := fmt.Sprintf("linking it into place: %v", err)
				if errors.Is(err, fs.ErrExist) {
					cause = "a file appeared at its name after heirygen read the directory, so it was not replaced"
				}
				// Put the old output back with a link too, which never
				// replaces a file: on a case-insensitive file system a file
				// that appeared at the new name has the old name as well.
				if restore := writer.link(aside, path(w.caseOf)); restore != nil {
					return fail(w, "%s; the old output was kept as %s, because putting it back as %s failed: %v; to recover it, move away the file now at %s, then rename %s to %s", cause, aside, w.caseOf, restore, path(w.name), aside, path(w.caseOf))
				}
				cleanup(aside)
				return fail(w, "%s; the old output %s was restored", cause, w.caseOf)
			}
			cleanup(w.temp)
			w.temp = ""
			cleanup(aside)
		}
		report.Written = append(report.Written, w.name)
	}
	for _, name := range removals {
		if keep[name] {
			continue
		}
		if now, err := os.Lstat(path(name)); err != nil || !stillSame(st.infos[name], now) {
			return report, fmt.Errorf("%s: it changed after heirygen read it, so the obsolete output was not removed; %s, and the obsolete outputs after it were not removed%s", path(name), progress(report), leftover())
		}
		if err := writer.remove(path(name)); err != nil {
			return report, fmt.Errorf("removing obsolete %s: %w; %s, and the obsolete outputs after it were not removed%s", path(name), err, progress(report), leftover())
		}
		report.Removed = append(report.Removed, name)
	}
	if len(left) != 0 {
		return report, fmt.Errorf("every output is up to date, but heirygen could not remove the hidden files %s, which the go command ignores: delete them", strings.Join(left, ", "))
	}
	return report, nil
}

// progress says what a run changed before it stopped.
func progress(report Report) string {
	var done []string
	if len(report.Written) != 0 {
		done = append(done, "already put in place: "+strings.Join(report.Written, ", "))
	}
	if len(report.Removed) != 0 {
		done = append(done, "already removed: "+strings.Join(report.Removed, ", "))
	}
	if len(done) == 0 {
		return "no output was put in place"
	}
	return strings.Join(done, "; ")
}
